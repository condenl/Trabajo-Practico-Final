$ErrorActionPreference='Stop'
$root=Split-Path $PSScriptRoot -Parent
$out=Join-Path $root 'Documentacion\EnterpriseArchitect'
$repo=([Runtime.InteropServices.Marshal]::GetActiveObject('EA.App')).Repository
if ($repo.ConnectionString -ne (Join-Path $root 'diagramas.EAP')) { throw 'Proyecto incorrecto' }
$specs=Get-Content (Join-Path $out 'sequences-reconciled.json') -Raw -Encoding UTF8 | ConvertFrom-Json
$manifest=Get-Content (Join-Path $out 'manifest.json') -Raw -Encoding UTF8 | ConvertFrom-Json
$backup=Join-Path $root ('Backup_EA_Sequences_'+(Get-Date -Format 'yyyyMMdd_HHmmss'))
New-Item -ItemType Directory -Path $backup | Out-Null
Copy-Item -LiteralPath (Join-Path $root 'diagramas.EAP') -Destination (Join-Path $backup 'diagramas.EAP')
foreach($s in $specs) {
    $m=$manifest | Where-Object code -eq $s.code
    if (!$m) { throw ('Diagrama no registrado: '+$s.code) }
    $d=$repo.GetDiagramByID($m.diagramId)
    $p=$repo.GetPackageByID($d.PackageID)
    if($p.Name -notlike ($s.code+' *') -or $d.Type -ne 'Sequence') { throw 'Destino fuera del paquete esperado' }
    $repo.CloseDiagram($d.DiagramID)
    # These four packages were generated by our importer and own only their sequence.
    $p.Diagrams.Refresh()
    if($p.Diagrams.Count -ne 1) { throw 'Paquete con otros diagramas; no modificar automáticamente' }
    for($i=$p.Elements.Count-1;$i -ge 0;$i--) { $p.Elements.DeleteAt($i,$false) }
    $p.Elements.Refresh(); $d.DiagramObjects.Refresh(); $d.DiagramLinks.Refresh()
    $d.Notes=$s.notes; [void]$d.Update()
    $elements=@{}
    foreach($n in $s.nodes) {
        $e=$p.Elements.AddNew($n.name,$n.kind); $e.Stereotype=$n.stereotype; [void]$e.Update()
        $elements[$n.key]=$e
        $o=$d.DiagramObjects.AddNew(('l={0};r={1};t=50;b=140;' -f $n.x,($n.x+$n.w)),'')
        $o.ElementID=$e.ElementID; [void]$o.Update()
    }
    foreach($l in $s.links) {
        $c=$elements[$l.source].Connectors.AddNew($l.name,'Sequence'); $c.SupplierID=$elements[$l.target].ElementID
        $c.DiagramID=$d.DiagramID; $c.SequenceNo=$l.sequence; $c.TransitionAction='Call'; $c.TransitionEvent='Synchronous'; [void]$c.Update()
        $dl=$d.DiagramLinks.AddNew('',''); $dl.ConnectorID=$c.ConnectorID; [void]$dl.Update()
    }
    [void]$d.Update(); $repo.ReloadDiagram($d.DiagramID)
    [void]$repo.GetProjectInterface().PutDiagramImageToFile($d.DiagramGUID,$m.file,1)
    Write-Output ('UPDATED '+$s.code)
}
$repo.RefreshModelView(0)
